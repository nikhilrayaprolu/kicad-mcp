"""Generate the `pins:` YAML block for RV1106G2/G3 QFN128 straight from datasheet Table 2-1
(pymupdf find_tables on Rockchip_RV1106_Datasheet_V2.2 pages 21-22). No hand transcription of names.
Usage: gen_pins_yaml.py <datasheet.pdf> <out.yaml.part>"""
import sys, re, json, pymupdf

pdf, out = sys.argv[1], sys.argv[2]
doc = pymupdf.open(pdf)
pins = {}
src_page = {}
for pn in (21, 22):
    for t in doc[pn - 1].find_tables().tables:
        for r in t.extract():
            for name, num in ((r[0], r[1]), (r[2], r[3])):
                if not num or num == "Pin":
                    continue
                num = num.strip()
                if not (num.isdigit() or num == "E-PAD"):
                    continue
                pins[num] = re.sub(r"\s*\n\s*", "", name.strip())
                src_page[num] = pn
        break  # first table on page 22 is the QFN table; the second is the BGA (RV1106) table

assert all(str(i) in pins for i in range(1, 129)), sorted(set(map(str, range(1, 129))) - set(pins))
assert "E-PAD" in pins

POWER = {
    "MIPI_AVDD1V8/GPIO7_VCC1V8", "GPIO4_VCC", "RTC_AVDD3V3", "SARADC_USB_AVDD1V8", "USB_AVDD3V3",
    "CODEC_AVDD1V8", "GPIO3_VCC", "DDR_PLL_AVDD1V8", "PMU_VCC3V3", "PMU_DVDD0V9",
    "OSC_AVDD1V8/PLL_AVDD1V8", "OSC_PLL_DVDD", "GPIO1_VCC3V3", "GPIO6_VCC",
    "OTP_AVDD1V8/ETH_AVDD1V8/TSADC_AVDD1V8", "ETH_AVDD3V3", "GPIO5_VCC", "CPU_DVDD",
}
GROUND = {"TVSS", "VSS", "CODEC_AVSS"}
CLOCK = {"OSC_XIN", "OSC_XOUT", "RTC_XIN", "RTC_XOUT"}
ANALOG_PREFIX = ("CODEC_", "USB_D", "USB_VBUSDET", "ETH_PHY_", "ETH_EXTR", "DRAM_ZQ", "SARADC_IN")

# IO power domain of signal pins, from the Luckfox Pico Pro/Max schematic symbol sections
# (U1A..U1C headers "PMU", "VCCIO1".."VCCIO7"); supply pin in parentheses.
def domain(n):
    n = int(n) if n.isdigit() else 0
    if n in (58, 59, 60, 62, 63, 64, 65): return "PMUIO (pin61 PMU_VCC3V3, 3.3V only)"
    if 72 <= n <= 80: return "VCCIO1 (pin81 GPIO1_VCC3V3, 3.3V only)"
    if n in (22, 23): return "VCCIO2 (pin24 SARADC_USB_AVDD1V8, 1.8V only)"
    if n in (38, 39, 40, 41, 42, 44, 45, 46, 47, 48): return "VCCIO3 (pin43 GPIO3_VCC, 1.8V/3.3V)"
    if n in (11, 12, 14, 15, 16, 17, 18): return "VCCIO4 (pin13 GPIO4_VCC, 1.8V/3.3V)"
    if n in (104, 105, 106, 107, 109, 110, 111, 112, 113, 114): return "VCCIO5 (pin108 GPIO5_VCC, 1.8V/3.3V)"
    if n in (83, 84, 85, 86, 87, 89, 90, 91, 92, 93, 94, 95): return "VCCIO6 (pin88 GPIO6_VCC, 1.8V/3.3V)"
    if 2 <= n <= 9 or 117 <= n <= 128: return "VCCIO7 (pin1 MIPI_AVDD1V8/GPIO7_VCC1V8, 1.8V only)"
    return None

def ptype(name):
    if name in POWER or name.startswith("DVDD_") or name.startswith("DDR_VDDQ_"): return "power_in"
    if name in GROUND: return "ground"
    if name in CLOCK: return "clock"
    if name.startswith(ANALOG_PREFIX): return "analog"
    return "io"

def q(s): return json.dumps(s)

lines = ["pins:  # src: Rockchip_RV1106_Datasheet_V2.2-20260602.pdf#p21-22 (Table 2-1, RV1106G2 & G3); generated by scripts/gen_pins_yaml.py"]
order = [str(i) for i in range(1, 129)] + ["E-PAD"]
for num in order:
    name = pins[num]
    t = ptype(name)
    fields = [f"name: {q(name)}", f"type: {t}"]
    if t == "io" or name.startswith("SARADC_IN"):
        gp = re.search(r"(GPIO?\d_[A-D]\d)_?([udz])?$", name)
        if gp:
            fields.append(f"gpio: {q(gp.group(1))}")
            if gp.group(2): fields.append(f"default_pull: {q({'u':'up','d':'down','z':'highZ'}[gp.group(2)])}")
        d = domain(num)
        if d: fields.append(f"io_domain: {q(d)}")
        if "MIPI_CSI_RX" in name: fields.append("diff_pair: true")
    if t == "analog" and ("USB_D" in name or "ETH_PHY" in name): fields.append("diff_pair: true")
    fields.append(f"src: \"Rockchip_RV1106_Datasheet_V2.2-20260602.pdf#p{src_page[num]}\"")
    key = q("EP") if num == "E-PAD" else num
    lines.append(f"  {key}: {{{', '.join(fields)}}}")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", len(order), "pins")
